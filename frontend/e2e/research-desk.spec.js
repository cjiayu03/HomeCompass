import { test, expect } from '@playwright/test';

for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
  test(`compact research desk and synchronized sidebar at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport);
    const homes = Array.from({ length: 8 }, (_, index) => ({ id: `desk-${index}`, address: `${100 + index} Bedok North Road`, town: 'Bedok', type: '4-room', price: 500000 + index * 10000, lat: 1.32 + index * .003, lng: 103.92 + index * .002, source: 'HDB resale evidence', sourceUpdated: '2026-09', sourceSemantics: 'historical_transaction', observedOn: '2026-09-01', floorAreaSqm: 93, storeyRange: '04 TO 06', score: 72, risks: [], highlights: [] }));
    await page.route('**/api/v1/**', route => {
      const path = new URL(route.request().url()).pathname;
      const payload = path === '/api/v1/auth/session' ? { user: null } : path === '/api/v1/homes' || path === '/api/v1/search' ? { items: homes, count: homes.length, total: 8, dataMode: 'live', hasMore: false } : path === '/api/v1/resources' ? { features: [], dataMode: 'live' } : path === '/api/v1/search/options' ? { towns: ['Bedok'], flatTypes: ['4-room'] } : { items: [] };
      return route.fulfill({ json: payload });
    });
    await page.route('https://*.tile.openstreetmap.org/**', route => route.abort());
    await page.goto('/explore');
    const first = page.locator('article[data-home-id="desk-0"]');
    await expect(first).toBeVisible({ timeout: 15000 });
    const dock = page.getByRole('navigation', { name: 'Main navigation' });
    await expect(dock.getByRole('link', { name: 'Saved', exact: true })).toBeVisible();
    const dockBox = await dock.boundingBox();
    expect(dockBox.y).toBeGreaterThan(viewport.height - 100);
    await expect(page.getByRole('button', { name: 'Show navigation' })).toHaveCount(0);
    const initialHeader = await page.locator('.explore-topbar').boundingBox();
    expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBe(true);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    const stage = await page.locator('.explore-stage').boundingBox();
    expect(stage.y).toBeLessThan(viewport.height * .42);
    expect(stage.y + stage.height).toBeGreaterThan(viewport.height - 100);
    expect(stage.y + stage.height).toBeLessThanOrEqual(dockBox.y);
    if (viewport.width >= 768) {
      const divider = page.getByRole('separator', { name: 'Resize map and sidebar' });
      const previousWidth = Number(await divider.getAttribute('aria-valuenow'));
      await divider.focus(); await page.keyboard.press('ArrowLeft');
      await expect(divider).toHaveAttribute('aria-valuenow', String(previousWidth + 24));
      const point = await divider.boundingBox();
      await page.mouse.move(point.x + point.width / 2, point.y + point.height / 2);
      await page.mouse.down(); await page.mouse.move(point.x - 40, point.y + point.height / 2); await page.mouse.up();
      expect(Number(await divider.getAttribute('aria-valuenow'))).toBeGreaterThan(previousWidth + 24);
    }
    const marker = await page.locator('.leaflet-marker-icon').first().elementHandle();
    await page.getByRole('textbox', { name: 'Search a town, street or amenity' }).fill('Bedok');
    expect(await marker.evaluate(element => element.isConnected)).toBe(true);
    await first.getByRole('button', { name: 'Details', exact: true }).click();
    const sidebar = page.locator('.explore-detail');
    await expect(sidebar).toBeVisible();
    expect(await page.locator('.explore-topbar').boundingBox()).toEqual(initialHeader);
    await expect(sidebar.getByRole('heading', { name: '100 Bedok North Road', exact: true })).toBeVisible();
    await sidebar.getByRole('button', { name: 'Next record' }).click();
    await expect(sidebar.getByRole('heading', { name: '101 Bedok North Road', exact: true })).toBeVisible();
    await expect(page.locator('.map-marker.selected')).toHaveCount(1);
    await expect(page.locator('.leaflet-marker-icon[title="101 Bedok North Road"] .map-marker')).toHaveClass(/selected/);
    expect(await page.locator('.dialog-backdrop').count()).toBe(0);
    await sidebar.getByRole('button', { name: 'Close record details' }).click();
    if (viewport.width < 768) await page.getByLabel('More search tools').click();
    await page.getByRole('button', { name: 'Full map', exact: true }).click();
    await expect(page.locator('.explore-desk--map')).toBeVisible();
    const map = await page.locator('.explore-map').boundingBox();
    expect(map.height).toBeGreaterThan(viewport.height * .95);
    const panel = page.getByRole('region', { name: 'Housing search sidebar' });
    await expect(panel).toBeVisible();
    await expect(panel.getByRole('button', { name: 'Filters', exact: true })).toBeVisible();
    const collapseButton = page.getByRole('button', { name: 'Collapse search sidebar' });
    const buttonBeforeHover = await collapseButton.boundingBox();
    const iconBeforeHover = await collapseButton.locator('svg').boundingBox();
    await collapseButton.hover();
    await expect.poll(() => collapseButton.boundingBox()).toEqual(buttonBeforeHover);
    await expect.poll(() => collapseButton.locator('svg').boundingBox()).toEqual(iconBeforeHover);
    await page.mouse.down();
    expect(await collapseButton.boundingBox()).toEqual(buttonBeforeHover);
    await page.mouse.move(viewport.width - 2, 2);
    await page.mouse.up();
    const panelBox = await panel.boundingBox();
    expect(panelBox.x).toBe(0);
    expect(panelBox.y).toBe(0);
    expect(panelBox.height).toBe(viewport.height);
    if (viewport.width >= 768) expect(panelBox.width).toBeLessThan(viewport.width * .3);
    const results = await page.locator('.explore-results').boundingBox();
    const controls = await page.locator('.explore-controls').boundingBox();
    expect(results.y).toBeGreaterThanOrEqual(controls.y + controls.height);
    expect(Math.abs(results.y + results.height - viewport.height)).toBeLessThan(3);
    const mapHeader = await page.locator('.explore-topbar').boundingBox();
    // Collapse preserves the query, loaded records and map instance.
    const fullMapNode = await page.locator('.leaflet-container').elementHandle();
    await page.getByRole('button', { name: 'Collapse search sidebar' }).click();
    await expect(panel).not.toBeVisible();
    await expect(page.getByRole('button', { name: 'Open search sidebar' })).toHaveAttribute('aria-expanded', 'false');
    expect(await fullMapNode.evaluate(element => element.isConnected)).toBe(true);
    await page.getByRole('button', { name: 'Open search sidebar' }).focus();
    await page.keyboard.press('Enter');
    await expect(panel).toBeVisible();
    await expect(panel.getByRole('textbox', { name: 'Search a town, street or amenity' })).toHaveValue('Bedok');
    await expect(first).toBeVisible();
    await first.getByRole('button', { name: 'Details', exact: true }).click();
    await expect(sidebar).toBeVisible();
    const detailsBox = await page.locator('.map-record-details').boundingBox();
    expect(Math.abs(detailsBox.x + detailsBox.width - viewport.width)).toBeLessThan(2);
    const mapOptions = page.getByLabel('Map options', { exact: true });
    await mapOptions.click();
    await expect(page.getByRole('heading', { name: 'Map view', exact: true })).toBeVisible();
    if (viewport.width >= 768) {
      const optionsBox = await mapOptions.boundingBox();
      expect(optionsBox.x + optionsBox.width).toBeLessThan(detailsBox.x);
    } else {
      await expect(page.locator('.detail-map-tools-host').getByLabel('Map options', { exact: true })).toBeVisible();
    }
    await mapOptions.click();
    if (viewport.width >= 768) await expect(first).toBeVisible();
    expect(await page.locator('.explore-topbar').boundingBox()).toEqual(mapHeader);
    await sidebar.getByRole('button', { name: 'Close record details' }).click();
    await first.getByRole('button', { name: /^Compare / }).click();
    const compareAction = page.getByRole('button', { name: 'Compare 1 selected records', exact: true });
    await expect(compareAction).toBeDisabled();
    const compareGroup = page.locator('.comparison-action-group');
    await expect(compareGroup).toHaveAttribute('data-ready', 'false');
    await expect(compareGroup).toHaveCSS('animation-name', 'none');
    if (viewport.width >= 768) await compareGroup.hover();
    else await page.getByRole('button', { name: 'Manage comparisons' }).click();
    const preview = page.locator('.comparison-preview');
    await expect(preview).toBeVisible();
    await preview.getByRole('button', { name: 'Remove 100 Bedok North Road from comparison', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Compare 0 selected records', exact: true })).toBeDisabled();
    await expect(preview.getByText('Choose Compare on a home to add it here.')).toBeVisible();
    await preview.getByRole('button', { name: 'Close comparison preview' }).click();
    await first.getByRole('button', { name: /^Compare / }).click();
    await page.locator('article[data-home-id="desk-1"]').getByRole('button', { name: /^Compare / }).click();
    const validCompare = page.getByRole('button', { name: 'Compare 2 selected records', exact: true });
    await expect(validCompare).toBeEnabled();
    await expect(validCompare).toHaveClass(/clear-button-primary/);
    await expect(compareGroup).toHaveCSS('animation-name', 'none');
    expect(await compareGroup.evaluate(element => element.getAnimations({ subtree: true }).every(animation => animation.effect.getTiming().iterations === 1))).toBe(true);
    await expect.poll(() => compareGroup.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await expect(compareGroup).toHaveCSS('animation-name', 'none');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    // Re-enabling motion also restarts the app's existing page-entry transition.
    await expect.poll(() => page.locator('.explore-topbar').boundingBox()).toEqual(mapHeader);
    await validCompare.click();
    await expect(page.getByRole('heading', { name: 'Compare your selected places', exact: true })).toBeVisible();
    expect(await page.locator('.comparison-tray').count()).toBe(0);
    expect(await page.locator('.dialog-backdrop').count()).toBe(1);
    expect(await page.locator('.explore-topbar').boundingBox()).toEqual(mapHeader);
    await page.getByRole('button', { name: 'Back to search', exact: true }).click();
    if (viewport.width < 768) await page.getByLabel('More search tools').click();
    await page.getByRole('button', { name: 'Split view', exact: true }).click();
    await expect(page.locator('.explore-desk--map')).toHaveCount(0);
  });
}
